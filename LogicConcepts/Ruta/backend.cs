
namespace Ruta
    {
        public class Ruta
        {
            // fields
            private int ruta1;
            private int ruta2;
            private int ruta3;
            private int ruta4;

            // constructor vacío
            public Ruta()
            {
                ruta1 = 0;
                ruta2 = 0;
                ruta3 = 0;
                ruta4 = 0;
            }

            // constructor con parámetros
            public Ruta(int ruta1, int ruta2, int ruta3, int ruta4)
            {
                this.ruta1 = ruta1;
                this.ruta2 = ruta2;
                this.ruta3 = ruta3;
                this.ruta4 = ruta4;
            }
        }
    }

